import { COLORS } from '../canvas/graph.js';
import { entryIcon, type ViewContext } from './context.js';

/** Markdown landing page: how to open the canvases, a legend and every entry point. */
export function readme(ctx: ViewContext): string {
  const md = (p: string) => `(${encodeURI(p)})`;
  const rows = [...ctx.spring.entries]
    .sort((a, b) => a.kind.localeCompare(b.kind) || a.trigger.localeCompare(b.trigger))
    .map((e) => `| ${entryIcon(e)} ${e.kind} | \`${e.trigger.replace(/\|/g, '\\|')}\` | ${e.method.owner.name}.${e.method.name}() | [flow]${md(ctx.paths.flow(e))} |`);
  const legend = Object.entries({
    'Inbound (REST, listeners, tools)': COLORS.inbound,
    Service: COLORS.service,
    'Outbound / database': COLORS.outbound,
    Model: COLORS.model,
    'Kafka topic / async': COLORS.kafka,
    'Retry / DLT / throw': COLORS.dlt,
    'LLM (Spring AI)': COLORS.llm,
    'Decision (flowchart)': COLORS.decision,
    'Loop (flowchart)': COLORS.loop,
  }).map(([k, v]) => `| ${k} | \`${v}\` |`);
  return [
    `# ${ctx.project.name} — code view`,
    '',
    'Generated by `java-canvas`. Open this folder (or the project root) as an Obsidian vault, or load the `.canvas` files in any [JSON Canvas](https://jsoncanvas.org) viewer.',
    '',
    `Start at [index.canvas]${md(ctx.paths.index)} and drill down:`,
    '',
    '1. **index.canvas** – system context: modules, inbound triggers, Kafka topics, databases, LLMs, HTTP services',
    ...(ctx.kafka.used ? ['2. **events.canvas** – Kafka producers → topics → consumers (incl. retry / DLT)'] : []),
    '3. **components/** – layered component diagram per module (Inbound → Service → Outbound → Model)',
    '4. **flows/** – call flow per entry point, calls numbered in order, async hops linked',
    '5. **methods/** – statement-level flowchart (if / loop / try / switch) of non-trivial methods',
    '',
    '## Legend',
    '',
    '| Meaning | Color |',
    '|---|---|',
    ...legend,
    '',
    `## Entry points (${rows.length})`,
    '',
    '| Kind | Trigger | Method | |',
    '|---|---|---|---|',
    ...rows,
    '',
  ].join('\n');
}
